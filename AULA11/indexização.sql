    id_fornecedor INT,
    id_produto INT,
    nome_fornecedor VARCHAR(100),
    telefone_fornecedor VARCHAR(20),
    nome_produto VARCHAR(100),
    preco_atual_produto DECIMAL(10,2),
    preco_compra DECIMAL(10,2),
    prazo_entrega_dias INT,
    PRIMARY KEY (id_fornecedor, id_produto)
);

-- EX 1: IDENTIFIQUE AS DEPENDENCIAS

-- DEPENDENCIAS:
-- id_fornecedor -> nome_fornecedor
-- id_fornecedor -> telefone_fornecedor

-- DEPENDENCIAS DO PRODUTO:
-- id_produto -> nome_produto
-- id_produto -> preco_atual_produto

-- DEPENDENCIAS DA RELACAO FORNECEDOR E PROADUTO:
-- (id_fornecedor, id_produto) -> preco_compra
-- (id_fornecedor, id_produto) -> prazo_entrega_dias

-- CHAVE PRIMARIA COMPOSTA:
-- (id_fornecedor, id_produto)

-- DEPENDENCIAS PARCIAIS:
-- nome_fornecedor e telefone_fornecedor dependem apenas de id_fornecedor.
-- nome_produto e preco_atual_produto dependem apenas de id_produto.

-- EX 2: REESTRUTURE 

CREATE TABLE FORNECEDOR (
    id_fornecedor INT PRIMARY KEY,
    nome_fornecedor VARCHAR(100),
    telefone_fornecedor VARCHAR(20)
);

CREATE TABLE PRODUTO (
    id_produto INT PRIMARY KEY,
    nome_produto VARCHAR(100),
    preco_atual_produto DECIMAL(10,2)
);

CREATE TABLE FORNECEDOR_PRODUTO (
    id_fornecedor INT,
    id_produto INT,
    preco_compra DECIMAL(10,2),
    prazo_entrega_dias INT,

    PRIMARY KEY (id_fornecedor, id_produto),

    FOREIGN KEY (id_fornecedor)
        REFERENCES FORNECEDOR(id_fornecedor),

    FOREIGN KEY (id_produto)
        REFERENCES PRODUTO(id_produto)
);

