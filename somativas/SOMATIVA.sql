CREATE DATABASE IF NOT EXISTS PROJETO_OFICINA;
USE PROJETO_OFICINA;

CREATE TABLE IF NOT EXISTS FUNCIONARIOS (
ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
CONTRATO TEXT,
DATA_DE_NASCIMENTO DATE,
CPF VARCHAR(11) NOT NULL UNIQUE,
TELEFONE VARCHAR(9) NOT NULL UNIQUE,
CARGO VARCHAR(20),
SALARIO DECIMAL(5,2) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS CLIENTES (
ID_CLIENTES INT AUTO_INCREMENT PRIMARY KEY,
ORCAMENTO FLOAT,
CPF VARCHAR(11) NOT NULL UNIQUE,
TELEFONE VARCHAR(9) NOT NULL UNIQUE,
DATA_DE_NASCIMENTO DATE,
NOME VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS SERVICOS (
ID_SERVICO INT AUTO_INCREMENT PRIMARY KEY,
TIPO_SERVICO VARCHAR(60),
ORCAMENTO TEXT,
PECAS VARCHAR(50),
AGENDAMENTO DATETIME,
TERMOS TEXT,
STATUS_SERVICO ENUM('ATIVO','INATIVO')
);

CREATE TABLE IF NOT EXISTS ORDENS_DE_SERVICO (
ID_ORDENS_DE_SERVICO INT AUTO_INCREMENT PRIMARY KEY,
POLIMENTO VARCHAR(60),
TROCA_DE_PECAS VARCHAR(60),
CONSERTO VARCHAR(50),
CALIBRAGEM VARCHAR(60),
TUNAGEM VARCHAR(60),
PINTURA VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS PECAS (
ID_PECA INT AUTO_INCREMENT PRIMARY KEY,
FORNECIMENTO VARCHAR(60),
PRECO FLOAT,
ORIGEM VARCHAR(50) NOT NULL UNIQUE,
QUANTIDADE INT,
TIPO_PECA VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS MARCAS (
ID_MARCA INT AUTO_INCREMENT PRIMARY KEY,
VALOR FLOAT,
TIPO_MARCA VARCHAR(50),
PAIS_ORIGEM VARCHAR(60),
NOME VARCHAR(60),
MODELO VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
ID_FORNECEDORES INT AUTO_INCREMENT PRIMARY KEY,
QUANTIDADE_FORNECIDA INT,
NOME VARCHAR(60),
VALOR FLOAT,
FORMA_FORNECIMENTO VARCHAR(60),
DATA_DE_ENTRAGA DATETIME
);

CREATE TABLE IF NOT EXISTS MODELO (
ID_MODELO INT AUTO_INCREMENT PRIMARY KEY,
VALOR FLOAT,
TIPO VARCHAR(60),
ANO_FABRICAÇÃO DATE,
NOME VARCHAR(60),
LUGAR_FABRICAÇÃO VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS PAGAMENTOS (
ID_PAGAMENTOS INT AUTO_INCREMENT PRIMARY KEY,
COMPROVANTE TEXT,
CONTRATO TEXT,
HORA_PAGAMENTO TIMESTAMP,
VALOR FLOAT,
FORMA_PAGAMENTO VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS VEICULO (
ID_VEICULO INT AUTO_INCREMENT PRIMARY KEY,
MARCA VARCHAR(60),
TIPO_VEICULO VARCHAR(60),
PLACA VARCHAR(8) NOT NULL UNIQUE,
PECAS VARCHAR(20),
MODELO VARCHAR(60)
);

