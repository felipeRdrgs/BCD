CREATE DATABASE IF NOT EXISTS SMARTCOFFE;
USE SMARTCOFFE;




CREATE TABLE IF NOT EXISTS CLIENTES (
ID_CLIENTES INT AUTO_INCREMENT PRIMARY KEY,
NOME VARCHAR(60),
CPF VARCHAR(11) NOT NULL UNIQUE,
EMAIIL VARCHAR(60),
IDADE INT
);

CREATE TABLE IF NOT EXISTS PROGRAMA_DE_FIDELIDADE(
ID_FIDELIDADE INT AUTO_INCREMENT PRIMARY KEY,
ASSINATURA TEXT,
VALOR FLOAT,
TERMOS TEXT,
CANCELAMENTO TEXT,
FORMA_DE_PAGAMENTO ENUM('DEBITO','CREDITO','PIX')
);

CREATE TABLE IF NOT EXISTS PAGAMENTO(
ID_PAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
FORMA_DE_PAGAMENTO ENUM('DEBITO','CREDITO','PIX','DINHEIRO'),
STATUS_PAGAMENTO ENUM('PAGO','PENDENTE'),
DESTINATARIO VARCHAR(60),
VALOR FLOAT,
DATA_PAGAMENTO TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FUNCIONARIOS(
ID_FUNCIONARIOS INT AUTO_INCREMENT PRIMARY KEY,
CARGA_HORARIA TIMESTAMP,
NOME VARCHAR(60),
CPF VARCHAR(14),
CARGO VARCHAR(60),
SALARIO FLOAT
);

CREATE TABLE IF NOT EXISTS DELIVERY(
ID_ENTREGA INT AUTO_INCREMENT PRIMARY KEY,
PREVISÃO_ENTREGA TIMESTAMP,
STATUS_ENTREGA ENUM('ENTREGA','NÃO ENTREGUE'),	
DESTINATARIO VARCHAR(60),
FORMA_DE_PAGAMENTO ENUM('DEBITO','CREDITO','PIX','DINHEIRO')
);

CREATE TABLE IF NOT EXISTS PEDIDOS(
ID_PEDIDO INT AUTO_INCREMENT PRIMARY KEY,
VALOR FLOAT,
QUANTIDADE INT,
NUMERO_DO_PEDIDO INT,
TIPO_DE_PEDIDO ENUM('COMUM','DELIVERY','AGENDADO'),
PRODUTOS TEXT,
TEMPO_PARA_FICA_PRONTO TIMESTAMP 
);

CREATE TABLE IF NOT EXISTS PRODUTOS(
ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
VALIDADE DATE,
NUMERO_PRODUTO INT,	
DATA_DE_FABRICACAO DATE,
TIPO_DE_PRODUTO VARCHAR(100),
QUANTIDADE INT
);

CREATE TABLE IF NOT EXISTS CATEGORIA(
ID_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
ESTRANGEIRO VARCHAR(60),
BEBIDAS ENUM('SEM ALCOOL','COM ALCOOL'),
DOCE VARCHAR(60),
SALGADOS VARCHAR(60),
CAFES VARCHAR (60)
);

CREATE TABLE IF NOT EXISTS ESTOQUE(
ID_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
QUANTIDADE INT,
LOTE VARCHAR(60),
DATA_DE_ENTRADA DATETIME,
ITENS_EM_ESTOQUE VARCHAR(60),
STATUS ENUM('DISPONIVEL','INDISPONIVEL')
);

