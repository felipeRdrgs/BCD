-- EX 9: ATUALIZAR PREÇO DO PRODUTO COM VALIDAÇÃO

DELIMITER $$

CREATE PROCEDURE ATUALIZAR_PRECO_PRODUTO (
    IN P_ID_PRODUTO INT,
    IN P_NOVO_PRECO DECIMAL(10,2)
)
BEGIN
    IF P_NOVO_PRECO > 0 THEN
        UPDATE PRODUTO
        SET PRECO = P_NOVO_PRECO
        WHERE ID_PRODUTO = P_ID_PRODUTO;

        SELECT 'PREÇO ATUALIZADO' AS MENSAGEM;
    ELSE
        SELECT 'PREÇO INVÁLIDO' AS MENSAGEM;
    END IF;
END $$

DELIMITER ;

CALL ATUALIZAR_PRECO_PRODUTO(2, 14);

SELECT * FROM PRODUTO;

-- EX 10: REGISTRAR PEDIDO COM TRANSAÇÃO

DELIMITER $$

CREATE PROCEDURE REGISTRAR_PEDIDO (
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;

    INSERT INTO PEDIDO (
        ID_CLIENTE,
        DATA_PEDIDO,
        STATUS_PEDIDO
    )
    VALUES (
        P_ID_CLIENTE,
        NOW(),
        'ABERTO'
    );

    SET P_ID_PEDIDO = LAST_INSERT_ID();

    COMMIT;
END $$

DELIMITER ;

CALL REGISTRAR_PEDIDO(1, @PEDIDO);

SELECT @PEDIDO;

-- EX 11: ADICIONAR ITEM AO PEDIDO

DELIMITER $$

CREATE PROCEDURE ADICIONAR_ITEM_PEDIDO (
    IN P_ID_PEDIDO INT,
    IN P_ID_PRODUTO INT,
    IN P_QUANTIDADE INT
)
BEGIN
    DECLARE V_PRECO DECIMAL(10,2);

    SELECT PRECO
    INTO V_PRECO
    FROM PRODUTO
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    INSERT INTO ITEM_PEDIDO (
        ID_PEDIDO,
        ID_PRODUTO,
        QUANTIDADE,
        PRECO_UNITARIO
    )
    VALUES (
        P_ID_PEDIDO,
        P_ID_PRODUTO,
        P_QUANTIDADE,
        V_PRECO
    );

    UPDATE ESTOQUE
    SET QUANTIDADE = QUANTIDADE - P_QUANTIDADE
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    SELECT 'ITEM ADICIONADO COM SUCESSO!' AS MENSAGEM;
END $$

DELIMITER ;

CALL ADICIONAR_ITEM_PEDIDO(1, 2, 3);