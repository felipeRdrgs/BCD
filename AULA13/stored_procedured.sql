CREATE PROCEDURE LISTAR_PRODUTOS()
BEGIN
    SELECT ID_PRODUTO AS CODIGO, NOME, PRECO
    FROM PRODUTO
    WHERE ATIVO = TRUE
    ORDER BY NOME;
END $$

DELIMITER ;

CALL LISTAR_PRODUTOS();

-- EX 3: PARÂMETROS IN - REPRESENTA UM VALOR ENVIADO PARA A
-- PROCEDURE

DELIMITER $$

CREATE PROCEDURE BUSCAR_PRODUTOS_CATEGORIA(IN P_ID_CATEGORIA INT)
BEGIN
    SELECT ID_PRODUTO AS CÓDIGO, NOME, PRECO
    FROM PRODUTO
    WHERE ID_CATEGORIA = P_ID_CATEGORIA
      AND ATIVO = TRUE
    ORDER BY NOME;
END $$

DELIMITER ;

CALL BUSCAR_PRODUTOS_CATEGORIA(3);

